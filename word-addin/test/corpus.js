// Word-style OMML runs (Word adds w:rPr with Cambria Math to every run).
const WRPR = '<w:rPr><w:rFonts w:ascii="Cambria Math" w:hAnsi="Cambria Math"/></w:rPr>';
const r = (t, sty) => `<m:r>${sty ? `<m:rPr><m:sty m:val="${sty}"/></m:rPr>` : ''}${WRPR}<m:t>${t}</m:t></m:r>`;
const ctrl = `<m:ctrlPr>${WRPR}</m:ctrlPr>`;
const e = x => `<m:e>${x}</m:e>`;

/** Wrap an equation's OMML the way Word's getOoxml() returns it: inside a paragraph in a package. */
export const wrapOmml = omml => `<pkg:package xmlns:pkg="http://schemas.microsoft.com/office/2006/xmlPackage">
<pkg:part pkg:name="/word/document.xml" pkg:contentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"><pkg:xmlData>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math">
<w:body><w:p><w:r><w:t xml:space="preserve">Text before </w:t></w:r>${omml}<w:r><w:t xml:space="preserve"> after.</w:t></w:r></w:p></w:body></w:document>
</pkg:xmlData></pkg:part></pkg:package>`;

